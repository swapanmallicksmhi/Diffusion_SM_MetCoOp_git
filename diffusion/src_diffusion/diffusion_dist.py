def create_diffusion(
    *,
    steps=4000,
    learn_sigma=False,
    sigma_small=False,
    noise_schedule="linear",
    use_kl=False,
    predict_xstart=False,
    rescale_timesteps=False,
    rescale_learned_sigmas=False,
    timestep_respacing="",
    diffusion_type="ddpm",
    sde_loss_type="score_mse",
    beta_min=0.1,
    beta_max=20.0,
    sampling_eps=1e-3,
    cfg_guidance_scale=1.5, #new_add
):
    if diffusion_type == "ddpm":
        return create_diffusion_gaussian(
            steps=steps,
            learn_sigma=learn_sigma,
            sigma_small=sigma_small,
            noise_schedule=noise_schedule,
            use_kl=use_kl,
            predict_xstart=predict_xstart,
            rescale_timesteps=rescale_timesteps,
            rescale_learned_sigmas=rescale_learned_sigmas,
            timestep_respacing=timestep_respacing,
        )

    elif diffusion_type == "vp_sde":
        if sde_loss_type == "score_mse":
            loss_type = SDELossType.SCORE_MSE
        elif sde_loss_type == "likelihood_weighted":
            loss_type = SDELossType.SCORE_MSE_LIKELIHOOD_WEIGHTED
        elif sde_loss_type == "snr_weighted": #snr_add
            if not hasattr(SDELossType, "SCORE_MSE_SNR_WEIGHTED"):
                raise ValueError(
                    "snr_weighted requires linking diffusion_sde_score_snr.py"
                )
            loss_type = SDELossType.SCORE_MSE_SNR_WEIGHTED
        else:
            raise ValueError(f"Unknown sde_loss_type: {sde_loss_type}")

        return VPSDE(
            beta_min=beta_min,
            beta_max=beta_max,
            loss_type=loss_type,
            rescale_timesteps=rescale_timesteps,
            sampling_eps=sampling_eps,
            num_timesteps=steps,
            cfg_guidance_scale=cfg_guidance_scale, #new_add
        )

    else:
        raise ValueError(f"Unknown diffusion_type: {diffusion_type}")

def create_diffusion_gaussian(
    *,
    steps=4000,
    learn_sigma=False,
    sigma_small=False,
    noise_schedule="linear",
    use_kl=False,
    predict_xstart=False,
    rescale_timesteps=False,
    rescale_learned_sigmas=False,
    timestep_respacing="",
):
    betas = gd.get_named_beta_schedule(noise_schedule, steps)
    if use_kl:
        loss_type = gd.LossType.RESCALED_KL
    elif rescale_learned_sigmas:
        loss_type = gd.LossType.RESCALED_MSE
    else:
        loss_type = gd.LossType.MSE
    if not timestep_respacing:
        timestep_respacing = [steps]
    print('loss_type', loss_type)
    print('timestep_respacing', [steps])
    return SpacedDiffusion(
        use_timesteps=space_timesteps(steps, timestep_respacing),
        betas=betas,
        model_mean_type=(
            gd.ModelMeanType.EPSILON if not predict_xstart else gd.ModelMeanType.START_X
        ),
        model_var_type=(
            (
                gd.ModelVarType.FIXED_LARGE
                if not sigma_small
                else gd.ModelVarType.FIXED_SMALL
            )
            if not learn_sigma
            else gd.ModelVarType.LEARNED_RANGE
        ),
        loss_type=loss_type,
        rescale_timesteps=rescale_timesteps,
    )


def add_dict_to_argparser(parser, default_dict):
    for k, v in default_dict.items():
        v_type = type(v)
        if v is None:
            v_type = str
        elif isinstance(v, bool):
            v_type = str2bool
        parser.add_argument(f"--{k}", default=v, type=v_type)


def args_to_dict(args, keys):
    return {k: getattr(args, k) for k in keys}


def str2bool(v):
    """
    """
    if isinstance(v, bool):
        return v
    if v.lower() in ("yes", "true", "t", "y", "1"):
        return True
    elif v.lower() in ("no", "false", "f", "n", "0"):
        return False
    else:
        raise argparse.ArgumentTypeError("boolean value expected")
